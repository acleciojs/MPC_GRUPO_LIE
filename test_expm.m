clc; clear;

import casadi.*

%% =========================================================
%% Dimensão
%% =========================================================
n = 5;

%% =========================================================
%% Gerar matriz antissimétrica (so(n))
%% =========================================================
A = randn(n);
S_num = A - A';   % garante S ? so(n)

%% =========================================================
%% Converter para CasADi
%% =========================================================
S = SX(S_num);

%% =========================================================
%% Calcular exponenciais
%% =========================================================
tic
R_casadi = full(expm_casadi(S));   % sua função
toc
tic
R_matlab = expm(S_num);            % referência MATLAB
toc
%% =========================================================
%% Erro
%% =========================================================
err = norm(R_casadi - R_matlab, 'fro')



%% =========================================================
%% Teste de ortogonalidade
%% =========================================================
orth_err = norm(R_casadi'*R_casadi - eye(n), 'fro')



