function resultado=testar_admm_precondicionado_qp()
% Testa ADMM escalar e precondicionado na MESMA QP convexa com igualdade
% local, desigualdade e consenso de dois estados. Requer qpOASES no CasADi.
clear resolver_admm_qps
H1=diag([0.2,8]);
H2=diag([30,0.1]);
f1=[-2;1];f2=[1;-1.5];
b1=struct('n',2,'id',(1:2)', 'H',H1,'f',f1, ...
    'Aeq',[1 1],'beq',0.1, ...
    'Aineq',zeros(0,2),'bineq',zeros(0,1), ...
    'lb',[-3;-3],'ub',[3;3], ...
    'Le',speye(2),'Ls',sparse(0,2));
b2=struct('n',2,'id',(1:2)', 'H',H2,'f',f2, ...
    'Aeq',zeros(0,2),'beq',zeros(0,1), ...
    'Aineq',[1 -1],'bineq',0.05, ...
    'lb',[-3;-3],'ub',[3;3], ...
    'Le',sparse(0,2),'Ls',speye(2));
blocos={b1,b2};
qcentr=qp_casadi_criar(H1+H2,b1.Aeq,b1.beq, ...
    b2.Aineq,b2.bineq,b1.lb,b1.ub,'qpoases',2000,'qp_teste_central');
[xstar,~,~,~]=qp_casadi_resolver(qcentr,f1+f2);
flag=1;
assert(flag>0,'QP centralizada nao resolvida');
opts=struct('rho',2,'max_iter',6000,'tol_abs',1e-9, ...
    'tol_rel',1e-9,'tol_gap_inf',1e-8,'solver','qpoases', ...
    'verbose',false,'verbose_every',200, ...
    'precond_power',0.5,'precond_clamp',[0.2 5]);
modos={'scalar','curvature','manual'};
resultado=struct();resultado.x_central=xstar;
for j=1:numel(modos)
    mode=modos{j};opts.precond_mode=mode;
    if strcmp(mode,'manual'),opts.precond_weights=[0.5;2];end
    [x,info]=resolver_admm_qps(blocos,opts);
    erro=norm(x-xstar,inf);
    fprintf('%-10s | it=%4d | gap=%.3e | erro_inf=%.3e | status=%d\n', ...
            mode,info.iter,info.gap_inf,erro,info.converged);
    assert(info.ok && info.converged && erro<=5e-5, ...
        'Teste ADMM %s nao atingiu a referencia central',mode);
    resultado.(mode)=struct('iter',info.iter,'erro_inf',erro, ...
        'gap',info.gap_inf,'pesos',{info.metric_weights});
end
fprintf('TESTE APROVADO: os 3 modos reproduzem a QP central.\n');
end
