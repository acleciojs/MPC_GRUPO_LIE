clear; clc;
import casadi.*

%% =========================================================
%% Dimensões
%% =========================================================
n = 2;
N = 4;

%% =========================================================
%% Variáveis simbólicas
%% =========================================================
G = SX.sym('G', n, n);
G_sym = {G};

param = SX.sym('p',2); % dummy (não usado)

%% =========================================================
%% Base da álgebra sl(2)
%% (matriz traço zero)
%% =========================================================
omega = SX.sym('omega',3);

S = [ omega(1), omega(2);
      omega(3), -omega(1) ];

%% =========================================================
%% Função custo
%% =========================================================
I = eye(n);
f = sumsqr(G - I);

%% =========================================================
%% (OPCIONAL) Restrição desigualdade
%% exemplo: ||G||^2 <= 5
%% =========================================================
g = param(1)*sumsqr(G) -  param(2)*5;

%% =========================================================
%% (OPCIONAL) Igualdade
%% =========================================================
h = []; % vazio

%% =========================================================
%% Criar solver simbólico
%% =========================================================
[sym_data, casadi_funs] = solver_IPM( ...
    f, G_sym, param, S, omega, g, h);

%% =========================================================
%% Inicialização
%% =========================================================
G0 = { [2 0; 0 0.5] }; % det = 1 ?

%% =========================================================
%% Rodar otimização
%% =========================================================
G_opt = run_optimization( ...
    sym_data, casadi_funs, G0, [1;1], 50, 1e-6);

%% =========================================================
%% Resultado
%% =========================================================
disp('Resultado final:')
disp(G_opt{1})

disp('Determinante:')
disp(det(G_opt{1}))